// icon16Cut.test.ts - MARK-05, measured (plan 81-02).
//
// WHAT MARK-05 ASKS. "A hand-authored 16px cut is what renders below 24px." The requirement
// exists because `tauri icon` cannot do this job: it resamples one master down the whole ladder,
// and a shape correct at 48 pixels is wrong at 16. So the claim this spec has to make is not
// "the small icon looks fine". It is TWO claims, and they need different instruments:
//
//   1. THE CUT IS CRISP AT ITS OWN SIZE. Rendered at 16 pixels it shows only the colours it
//      declares, every pixel fully opaque, nothing blended. That is what "authored for the size"
//      means as a number, and it is measured against the MASTER rendered in the same call, which
//      is not crisp there. A zero-blend result is a property of a drawing authored on the grid it
//      is rendered at, not a property every SVG has, so without the control the first case would
//      be a measurement that cannot fail.
//
//   2. THE CUT IS AUTHORED, NOT RESAMPLED (D-04). This one is geometry and no raster can see it.
//      A downscale of the master would put EVERY part at exact half scale. The committed cut has
//      the cell and the item at exact half scale and the belt deliberately NOT: it is three units
//      tall rather than four and painted solid rather than filled inside a stroke, because at
//      16px the master's filled-and-stroked band renders as a 1px hollow outline with a dark
//      interior and competes with the cell frame. Asserting the DEPARTURE is what proves the cut
//      was drawn rather than scaled, and it is the only assertion in this phase that can detect
//      a violation of D-04.
//
// IF YOU HAVE JUST REDDENED THE DEPARTURE CASE, READ THIS BEFORE YOU EDIT IT. A red there almost
// certainly means the 16 unit cut was regenerated by resampling the master, which is the one
// thing MARK-05 forbids. The fix is in the generator, not here.
//
// NO TRANSCRIBED COLOUR AND NO REMEMBERED PERCENTAGE ANYWHERE BELOW. The authored colour set is
// PARSED OUT OF THE COMMITTED CUT'S OWN PAINT ATTRIBUTES, so the assertion is "the render shows
// only what the file declares" rather than "the render shows three particular values". A colour
// written into a spec is a second declaration of the palette that drifts the first time a ramp
// step moves, and a threshold literal stops being a measurement the moment the rasteriser or the
// render size changes. Both are the shape `markErasure.test.ts:17-23` refuses.
//
// THE RASTERISER IS PINNED. `@resvg/resvg-js` 2.6.2, the napi binding, the same one
// `scripts/build-icons.ts` writes every PNG through. The `/usr/bin/resvg` CLI on a developer box
// wraps a NEWER core and produces different bytes for the same source.
//
// No `@vitest-environment` docblock. The project default is the node environment, and that is
// what lets this spec import a module which resolves its paths from `import.meta.url`. A jsdom
// spec touching disk would have to use `import.meta.dirname` instead, the trap documented three
// times at `render/assets/vertexBudget.test.ts:66-92`.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { describe, expect, it } from 'vitest';
import {
  ICON_16_PATH,
  MASTER_PATH as GENERATOR_MASTER_PATH,
  RASTER_16_PATH,
  RASTER_24_PATH,
  rasterise,
} from '../../../scripts/build-icons.ts';
import { parseIconParts } from '../../chrome/svgToElements.ts';

/** The 16 unit optical cut: the subject. */
const CUT_16_PATH = fileURLToPath(
  new URL('../../../../docs/brand/fabrico-icon-16.svg', import.meta.url),
);

/**
 * THE CONTROL, and it is a committed drawing rather than a constructed one.
 *
 * The 32 unit master. It is the drawing the 16 unit cut would have been resampled FROM, which
 * makes it the right negative subject twice over: it is not crisp at 16 pixels (case 2), and it
 * is the half-scale reference every geometry case below is measured against (cases 3 and 4).
 */
const MASTER_PATH = fileURLToPath(
  new URL('../../../../docs/brand/fabrico-icon-master.svg', import.meta.url),
);

/** The size the optical cut was authored for. One author unit lands on one device pixel here. */
const SMALL_WIDTH = 16;

/** An axis-aligned box in author units. */
interface Box {
  x0: number;
  y0: number;
  x1: number;
  y1: number;
}

/** The painted extent of one layer: its outer contour, and its hole if it has one. */
interface Ring {
  outer: Box;
  inner: Box | null;
}

/**
 * The subpath boxes of a `d` string in the `M x y H x V y Z` dialect these files use.
 *
 * A CLOSED COMMAND SET, and the throw is load-bearing rather than defensive. A parser that
 * silently ignored a command it did not know would return a box for a drawing it had only
 * partly read, and every comparison below would then be measuring a fiction. Both committed
 * subjects are authored in this dialect on purpose (`lint-svg.ts` refuses curves in the chrome
 * dialect and the icon cuts follow it), so an unknown command means the artwork changed shape
 * and the instrument must say so rather than guess.
 */
function subpathBoxes(d: string): Box[] {
  const tokens = d.trim().split(/\s+/);
  const boxes: Box[] = [];
  let box: Box | null = null;
  let x = 0;
  let y = 0;

  const grow = (): void => {
    if (box === null) throw new Error(`icon16Cut: a drawing command precedes the first M in "${d}"`);
    box.x0 = Math.min(box.x0, x);
    box.y0 = Math.min(box.y0, y);
    box.x1 = Math.max(box.x1, x);
    box.y1 = Math.max(box.y1, y);
  };

  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    if (t === 'M') {
      x = Number(tokens[++i]);
      y = Number(tokens[++i]);
      box = { x0: x, y0: y, x1: x, y1: y };
    } else if (t === 'H') {
      x = Number(tokens[++i]);
      grow();
    } else if (t === 'V') {
      y = Number(tokens[++i]);
      grow();
    } else if (t === 'Z') {
      if (box === null) throw new Error(`icon16Cut: Z with no open subpath in "${d}"`);
      boxes.push(box);
      box = null;
    } else {
      throw new Error(
        `icon16Cut: unsupported path command "${t}" in "${d}". This helper reads the ` +
          'M / H / V / Z dialect both committed cuts are authored in, and refuses anything else ' +
          'rather than returning a box for a drawing it only partly read.',
      );
    }
  }
  if (boxes.length === 0) throw new Error(`icon16Cut: no closed subpath in "${d}"`);
  return boxes;
}

/** A box grown outward by `by` on every side. Negative shrinks it. */
function expand(b: Box, by: number): Box {
  return { x0: b.x0 - by, y0: b.y0 - by, x1: b.x1 + by, y1: b.y1 + by };
}

/**
 * The PAINTED extent of one named layer of one file, hole included.
 *
 * Two constructions, because the two files draw the same picture two different ways and the
 * comparison has to be between what is PAINTED rather than between what is written:
 *
 *   - A STROKED layer paints its contour widened by half the stroke on each side. If it is also
 *     `fill="none"` the interior is a hole, so the ring is the contour widened outward and the
 *     same contour narrowed inward. That is the master's cell.
 *   - An UNSTROKED layer paints its subpaths as written. A second subpath is its hole, which is
 *     how the 16 unit cut draws the same frame with no stroke at all.
 */
function paintedRing(svgText: string, part: string): Ring {
  const found = parseIconParts(svgText).find((p) => p.part === part);
  if (found === undefined) throw new Error(`icon16Cut: no part named ${part} in this drawing`);

  const boxes = subpathBoxes(found.d);
  const first = boxes[0] as Box;
  const stroke = found.stroke?.trim();
  const hasStroke = stroke !== undefined && stroke !== 'none';

  if (hasStroke) {
    const half = Number(found.strokeWidth ?? '0') / 2;
    if (!(half > 0)) throw new Error(`icon16Cut: part ${part} is stroked with no usable width`);
    const hollow = found.fill?.trim() === 'none';
    return { outer: expand(first, half), inner: hollow ? expand(first, -half) : null };
  }
  return { outer: first, inner: boxes.length > 1 ? (boxes[1] as Box) : null };
}

/** A box at half scale, which is what a resample of the master would produce. */
function half(b: Box): Box {
  return { x0: b.x0 / 2, y0: b.y0 / 2, x1: b.x1 / 2, y1: b.y1 / 2 };
}

function area(b: Box): number {
  return (b.x1 - b.x0) * (b.y1 - b.y0);
}

function width(b: Box): number {
  return b.x1 - b.x0;
}

function height(b: Box): number {
  return b.y1 - b.y0;
}

/** The paint values a file DECLARES, as the `r,g,b,a` strings a render reports. */
function declaredColours(svgText: string): Set<string> {
  const out = new Set<string>();
  for (const part of parseIconParts(svgText)) {
    for (const value of [part.fill, part.stroke]) {
      if (value === undefined) continue;
      const v = value.trim().toLowerCase();
      if (v === 'none' || !v.startsWith('#')) continue;
      const h = v.slice(1);
      out.add(
        `${parseInt(h.slice(0, 2), 16)},${parseInt(h.slice(2, 4), 16)},${parseInt(h.slice(4, 6), 16)},255`,
      );
    }
  }
  return out;
}

/**
 * One render at `SMALL_WIDTH`: how many pixels are NOT one of the file's own authored colours,
 * how many are not fully opaque, and how many there are in total.
 *
 * The blended count is the whole measurement. A drawing authored on the grid it is rendered at
 * puts every edge on a pixel boundary and produces none; a drawing rendered at half its author
 * size produces them at every edge that fell between two pixels.
 */
function blendedAtSmallSize(svgText: string): {
  blended: number;
  translucent: number;
  pixels: number;
} {
  const declared = declaredColours(svgText);
  const img = new Resvg(svgText, { fitTo: { mode: 'width', value: SMALL_WIDTH } }).render();
  const px = img.pixels;
  let blended = 0;
  let translucent = 0;
  for (let i = 0; i < px.length; i += 4) {
    const rgba = `${px[i]},${px[i + 1]},${px[i + 2]},${px[i + 3]}`;
    if (!declared.has(rgba)) blended++;
    if (px[i + 3] !== 255) translucent++;
  }
  return { blended, translucent, pixels: px.length / 4 };
}

const CUT_16 = readFileSync(CUT_16_PATH, 'utf8');
const MASTER = readFileSync(MASTER_PATH, 'utf8');

/** Every layer this spec measures on both files, so the floor covers exactly what the cases use. */
const PARTS = ['plate', 'rail', 'cell', 'item'] as const;

describe('MARK-05 - the 16 unit cut is authored for its size, not resampled to it', () => {
  it('THE FLOOR: every part of both files yields a box of non-zero area', () => {
    // Asserted first and as a case in its own right. A helper that returned an empty or
    // degenerate box would make every equality below compare two zeroes and pass for free,
    // which is the vacuous shape this repository has found fourteen times.
    expect(PARTS.length, 'the part list is empty, so every case below is vacuous').toBeGreaterThan(
      0,
    );
    for (const part of PARTS) {
      for (const [name, svg] of [
        ['the 16 unit cut', CUT_16],
        ['the master', MASTER],
      ] as const) {
        const ring = paintedRing(svg, part);
        expect(area(ring.outer), `${name} painted ${part} with zero area`).toBeGreaterThan(0);
        if (ring.inner !== null) {
          expect(area(ring.inner), `${name} gave ${part} a hole of zero area`).toBeGreaterThan(0);
        }
      }
    }
    // And both cells DO have a hole, which is what cases 3 and 4 compare. A cell that lost its
    // hole would otherwise skip the inner comparison silently.
    expect(paintedRing(CUT_16, 'cell').inner, 'the 16 unit cell has no hole').not.toBeNull();
    expect(paintedRing(MASTER, 'cell').inner, 'the master cell has no hole').not.toBeNull();
  });

  it('renders at its own size with no blended pixel and nothing translucent', () => {
    const { blended, translucent, pixels } = blendedAtSmallSize(CUT_16);

    expect(pixels, 'the cut rendered zero pixels, so this case is vacuous').toBeGreaterThan(0);
    expect(declaredColours(CUT_16).size, 'the cut declares no paint at all').toBeGreaterThan(0);

    // THE LOAD-BEARING LINES. Every pixel is one of the colours the file itself declares, and
    // every pixel is fully opaque, which is the plate doing its job (D-08).
    expect(blended, 'the 16 unit cut rendered a colour it does not declare').toBe(0);
    expect(translucent, 'the 16 unit cut rendered a pixel that is not fully opaque').toBe(0);
  });

  it('THE CONTROL, measured in the same run: the master is NOT crisp at that size', () => {
    // This is the case that makes the one above mean something. Same binding, same render
    // width, same run - and the 32 unit master, whose edges fall between device pixels at 16
    // pixels, blends. If a future rasteriser ever renders the master cleanly at this size, this
    // case reddens by name rather than quietly ceasing to discriminate.
    const master = blendedAtSmallSize(MASTER);
    const cut = blendedAtSmallSize(CUT_16);

    expect(master.pixels, 'the master rendered zero pixels, so this case is vacuous').toBeGreaterThan(
      0,
    );
    expect(master.pixels, 'the two subjects were not rendered at the same size').toBe(cut.pixels);

    expect(
      master.blended,
      'the master rendered no blended pixel at 16px, so the crispness case above no longer discriminates',
    ).toBeGreaterThan(0);
    expect(cut.blended, 'the cut is not strictly crisper than the master').toBeLessThan(
      master.blended,
    );
  });

  it('the cell and the item ARE exact half scale of the master', () => {
    // The half of D-04 that says the cut is the SAME MARK. If these drifted, the small icon
    // would be a different drawing rather than the same one authored for a smaller grid.
    const cut = { cell: paintedRing(CUT_16, 'cell'), item: paintedRing(CUT_16, 'item') };
    const master = { cell: paintedRing(MASTER, 'cell'), item: paintedRing(MASTER, 'item') };

    expect(master.cell.inner, 'the master cell has no hole, so the comparison below is vacuous').not.toBeNull();
    expect(cut.cell.inner, 'the 16 unit cell has no hole, so the comparison below is vacuous').not.toBeNull();

    expect(cut.cell.outer, 'the cell outer box is not half the master').toEqual(half(master.cell.outer));
    expect(cut.cell.inner, 'the cell hole is not half the master').toEqual(half(master.cell.inner as Box));
    expect(cut.item.outer, 'the item box is not half the master').toEqual(half(master.item.outer));
  });

  it('THE DECLARED DEPARTURE: the belt is NOT half scale, and the difference is its height', () => {
    // D-04's ENFORCEMENT, and the only assertion in this phase that can detect a resample.
    //
    // If somebody regenerates the 16 unit cut by scaling the master down, all four parts land
    // at exact half scale and this case goes RED. That is the point. The belt is a deliberate
    // optical departure: three units tall rather than four, and painted as a solid ink bar
    // rather than a panel fill inside an ink stroke, because at 16px the master's band renders
    // as a 1px hollow outline with a dark interior and reads as a second outlined rectangle
    // competing with the cell frame.
    //
    // A READER WHO HAS JUST REDDENED THIS HAS RESAMPLED, NOT FOUND A BUG. Fix the generator.
    const cut = paintedRing(CUT_16, 'rail');
    const master = paintedRing(MASTER, 'rail');
    const scaled = half(master.outer);

    expect(area(cut.outer), 'the belt has zero area, so this case is vacuous').toBeGreaterThan(0);
    expect(area(scaled), 'the scaled belt has zero area, so this case is vacuous').toBeGreaterThan(0);

    // THE LOAD-BEARING LINE.
    expect(cut.outer, 'the 16 unit belt IS an exact half scale copy of the master, which means this cut was resampled rather than authored (D-04)').not.toEqual(scaled);

    // And the difference is where the decision was taken: same width, shorter.
    expect(width(cut.outer), 'the belt changed width, which is not the recorded departure').toBe(
      width(scaled),
    );
    expect(height(cut.outer), 'the belt is not shorter than half the master').toBeLessThan(
      height(scaled),
    );

    // The belt is solid, not hollow: no stroke, so no hole. This is the other half of the same
    // optical fix and it is what a resample could not produce either.
    expect(cut.inner, 'the 16 unit belt has a hole, so it was drawn as a band not a bar').toBeNull();
  });
});

/* ------------------------------------------------------------------ *
 * MARK-05 CLAUSE 2: the hand cut is what SHIPS below 24px (post-review correction, 2026-09-09)
 * ------------------------------------------------------------------ */

/**
 * The two shipped rasters this gate is about, reached through the GENERATOR'S OWN constants.
 *
 * WHY THIS BLOCK EXISTS, and it is the half of MARK-05 that was true and asserted nowhere.
 * MARK-05 has two clauses: "a 16px optical cut is authored by hand rather than scaled down from
 * the full cut" AND "is what renders below 24px". Everything above this line proves the first:
 * the drawing exists, it is crisp at its own size, and its belt provably departs from a half
 * scale copy. NOTHING proved the second. It rested entirely on two un-asserted literals in
 * `LADDER` (`scripts/build-icons.ts`, the `cut: 'small'` entries for 16 and 24), and `LADDER` is
 * SOURCE rather than a test: flipping both to `'master'` and running `npm run build:icons` ships
 * a plain master downscale in place of the hand cut, and the unit suite, `tsc --noEmit`,
 * `lint:svg` and `check:mark-craft` all stayed green on the mutant. MEASURED, in a detached
 * worktree, not argued.
 *
 * THE GATE BINDS BYTES TO PROVENANCE, IN BOTH DIRECTIONS, and one direction alone would not do
 * it. "The shipped PNG is a 16px render of the hand cut" would pass for free if the hand cut and
 * the master happened to render identically at that size, which is exactly the state a careless
 * regeneration produces. So the second assertion says the shipped PNG is NOT a render of the
 * master. Together they are a claim about WHICH DRAWING FED THE FILE rather than about bytes.
 *
 * `48x48.png` IS MASTER DERIVED ON PURPOSE AND IS NOT ASSERTED HERE. Plan 81-04 measured zero
 * blended pixels for the master at 48, so a hand cut buys nothing there and the ladder is right
 * to take it off the master. That is why this block names 16 and 24 rather than walking `LADDER`:
 * walking the table would assert the table against itself, which is the tautology this file
 * exists to avoid.
 *
 * RENDERED THROUGH THE GENERATOR'S OWN `rasterise`, deliberately. Byte identity against a PNG
 * is only meaningful on the binding that wrote it, and the header of `scripts/build-icons.ts`
 * records that the `/usr/bin/resvg` CLI on a developer box wraps a NEWER core and emits
 * different bytes for the same source. Re-deriving the render options here would make this gate
 * red on a legitimate generator change while proving nothing extra.
 */
const SHIPPED_SMALL_RASTERS = [
  { name: '16x16.png', path: RASTER_16_PATH, width: 16 },
  { name: '24x24.png', path: RASTER_24_PATH, width: 24 },
] as const;

describe('MARK-05 clause 2 - the hand cut is what the installer set ships below 24px', () => {
  it('THE FLOOR: this spec and the generator name the same two drawings, and they render differently', () => {
    // Half one. This file derives its SVG paths from its own `import.meta.url` and the generator
    // derives its own. If the two ever pointed at different files, every case below would be
    // comparing the shipped raster against a drawing the generator does not use, and would say
    // nothing at all about what ships.
    expect(ICON_16_PATH, 'this spec and the generator disagree about the 16 unit cut').toBe(
      CUT_16_PATH,
    );
    expect(GENERATOR_MASTER_PATH, 'this spec and the generator disagree about the master').toBe(
      MASTER_PATH,
    );

    // Half two, and it is what stops the `not` assertions below passing for free. If the two
    // drawings rendered to the same bytes at these sizes, "the shipped file is not a master
    // render" would be satisfied by a master render, and the whole block would be vacuous.
    for (const { name, width } of SHIPPED_SMALL_RASTERS) {
      const fromCut = rasterise(CUT_16, width);
      const fromMaster = rasterise(MASTER, width);
      expect(fromCut.length, `the cut rendered zero bytes at ${width}px`).toBeGreaterThan(0);
      expect(fromMaster.length, `the master rendered zero bytes at ${width}px`).toBeGreaterThan(0);
      expect(
        fromCut.equals(fromMaster),
        `the cut and the master render identically at ${width}px, so the provenance case for ${name} cannot fail`,
      ).toBe(false);
    }
  });

  for (const { name, path, width } of SHIPPED_SMALL_RASTERS) {
    it(`${name} IS the hand cut rendered at ${width}px, and is NOT the master downscaled`, () => {
      // A READER WHO HAS JUST REDDENED THIS HAS SHIPPED A DOWNSCALE, NOT FOUND A BUG. The fix is
      // `LADDER` in `scripts/build-icons.ts` followed by `npm run build:icons`, never this file.
      const shipped = readFileSync(path);
      expect(shipped.length, `${name} is empty on disk, so this case is vacuous`).toBeGreaterThan(0);

      // THE LOAD-BEARING PAIR.
      expect(
        shipped.equals(rasterise(CUT_16, width)),
        `${name} is not a ${width}px render of the hand authored 16 unit cut, so MARK-05's second clause is broken: either the ladder stopped feeding it the small cut or the icons are stale (regenerate with npm run build:icons)`,
      ).toBe(true);
      expect(
        shipped.equals(rasterise(MASTER, width)),
        `${name} IS a plain ${width}px downscale of the master, which is precisely what MARK-05 forbids below 24px`,
      ).toBe(false);
    });
  }
});
