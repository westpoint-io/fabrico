import { test, expect, type Page } from '@playwright/test';
import { copyFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  captureRefusalText,
  drawnNodesOf,
  ensurePlaying,
  expectRenderLoopAlive,
  glyphSubjectOn,
  newBoard,
  pollScene,
  readScene,
  screenCellCentre,
  waitForAppReady,
  waitForCameraSettle,
  watchPageErrors,
  type SceneFacts,
} from './support/oracle';

// 86-undo-space-taken.live.spec.ts (plan 86-06, D-04, WORK-02) - a user opens a board whose
// last Delete would come back over a Source, and presses Ctrl+Z. The Undo is refused with a
// plain sentence, nothing is placed, Undo is still offered, and the board saves and opens
// again. On the REAL host (dev_render_server, real Core -> RenderProducer -> postcard ->
// WS). Zero mocks, zero injected packets.
//
// WHY A FORGED FILE. With linear undo no ordinary gesture reaches this guard: anything placed
// after a Delete is undone before the Delete is, and plan 86-02's turned restore puts a turned
// machine back on exactly the cells it held. The guard keeps every board loadable against a
// forged or corrupted history, so the one way to meet it is a file whose history is forged.
// `crates/fabrico-host/tests/fixtures/86-undo-space-taken.fab` is a real host board (a
// Factory at (20,20) and a Source at (23,20), the Factory deleted last) with ONE field
// changed: the Delete's captured box is 4 columns wide instead of 3, so the box Ctrl+Z would
// put back reaches the Source's cell. It is GENERATED by `crates/fabrico-host/tests/
// forged_files.rs`, whose currency test requires the committed bytes equal a fresh build.
//
// WHAT IS GRADED IS WHAT THE USER SEES: the sentence in the refusal band, the board the model
// holds (one Source on (23,20), no Factory), the machine layer drawing exactly that Source,
// the Undo button still enabled, and a Save then Open of the board with no refusal card.
// After the sentence the board is read once it has ticked on, so an Undo the host accepted
// would have echoed by then.
//
// RED ON THE UNCHANGED HOST (plan 86-06 task 1, `space-red.*`): no sentence, the Factory came
// back over the Source, and the saved board was refused on open. The post-Ctrl+Z grades are
// soft so the red names every one of those facts, not only the first.
//
// Render health in the test (fabrico-model-oracle-blindspot): `watchPageErrors` before
// `page.goto`, `expectRenderLoopAlive` after every step.
//
// Drive rules: the real Open and Save buttons and the browser prompt dialog, the real Ctrl+Z
// key; every wait polls a specific change, never a fixed sleep.

/** The committed forged board. */
const FIXTURE = fileURLToPath(
  new URL('../../crates/fabrico-host/tests/fixtures/86-undo-space-taken.fab', import.meta.url),
);

/** The refusal sentence (`REFUSAL_COPY.UndoSpaceTaken`), transcribed rather than imported:
 *  the live suite imports no product source. */
const SENTENCE = 'That space is taken now. Nothing was undone.';

/** Kind bytes (protocol `machine_kind`). */
const KIND_SOURCE = 0;
const KIND_FACTORY = 2;

/** The Source's cell, and an empty floor cell clear of every node. */
const SOURCE_AT: [number, number] = [23, 20];
const FLOOR_AT: [number, number] = [14, 14];

type NodeFacts = SceneFacts['nodes'][number];

/** A node's cells, sorted row-major, as `x,y` strings. */
function sortedCells(node: NodeFacts): string[] {
  return [...node.cells].sort((a, b) => a[1] - b[1] || a[0] - b[0]).map(([x, y]) => `${x},${y}`);
}

/** What the user sees of the board: every node's kind and cells, the belt and cable counts. */
function boardOf(scene: SceneFacts): { nodes: { kind: number; cells: string[] }[]; belts: number; wires: number } {
  const nodes = scene.nodes
    .map((n) => ({ kind: n.kind, cells: sortedCells(n) }))
    .sort((a, b) => a.kind - b.kind || a.cells.join(';').localeCompare(b.cells.join(';')));
  return { nodes, belts: scene.belts.length, wires: scene.wires.length };
}

/** The board this file holds once it is open: one Source on (23,20) and nothing else. */
const ONLY_THE_SOURCE = {
  nodes: [{ kind: KIND_SOURCE, cells: [`${SOURCE_AT[0]},${SOURCE_AT[1]}`] }],
  belts: 0,
  wires: 0,
};

/** The toolbar's Undo control. */
function undoButton(page: Page) {
  return page.getByRole('button', { name: 'Undo', exact: true });
}

/** Open `fab` through the toolbar's Load button and its prompt. */
async function openThroughToolbar(page: Page, fab: string): Promise<void> {
  page.once('dialog', (d) => void d.accept(fab));
  await page.getByTitle('Load a saved factory').click();
}

test.describe('D-04 live: an Undo that would land on another machine is refused in words and changes nothing', () => {
  test('opening a board whose last Delete would come back over a Source, Ctrl+Z says the space is taken, the Source keeps its cell, nothing is drawn over it, Undo stays offered, and the board reopens', async ({
    page,
  }) => {
    test.setTimeout(120_000);
    const errs = watchPageErrors(page);
    await page.setViewportSize({ width: 1280, height: 800 });
    await page.goto('/');
    await waitForAppReady(page);
    await expectRenderLoopAlive(page, 'on the board the app boots');

    // OPEN THE FORGED BOARD, a private copy so the host opens a file nothing else writes.
    const stamp = Date.now();
    const opened = join(tmpdir(), `fabrico-e2e-86-undo-space-taken-${stamp}.fab`);
    copyFileSync(FIXTURE, opened);
    await openThroughToolbar(page, opened);
    await pollScene(page, boardOf, {
      message: 'the forged board opened: one Source on (23,20), the Factory deleted',
    }).toEqual(ONLY_THE_SOURCE);
    await expect(page.getByRole('alert'), 'no refusal card: the forged board opens').toHaveCount(0);
    await ensurePlaying(page);
    await waitForCameraSettle(page);
    await expectRenderLoopAlive(page, 'on the opened board');
    const source = (await readScene(page)).nodes.find((n) => n.kind === KIND_SOURCE)!;
    await expect
      .poll(async () => {
        const d = await drawnNodesOf(page);
        return { machines: d.machines, strays: d.strays };
      }, { message: 'the machine layer draws the one Source the model holds' })
      .toEqual({ machines: [source.id], strays: 0 });
    await expect(undoButton(page), 'the opened board offers Undo (its last step is the Delete)').toBeEnabled();

    // CTRL+Z, after a floor click so the key goes to the board and not the toolbar.
    const floor = await screenCellCentre(page, FLOOR_AT[0], FLOOR_AT[1]);
    await page.mouse.click(floor.x + 3, floor.y - 2);
    const tickAtPress = (await readScene(page)).tick;
    await page.keyboard.press('Control+z');

    // (1) THE SENTENCE the user reads.
    const said = await captureRefusalText(page, 'Ctrl+Z was answered with a refusal sentence', { soft: true });
    expect.soft(said, 'the refusal says the space is taken and nothing was undone').toBe(SENTENCE);

    // (2) THE BOARD, read once the host has ticked on past the press.
    await pollScene(page, (s) => s.tick, {
      message: `the board ticks on after the Ctrl+Z (tick ${tickAtPress} at the press)`,
    }).toBeGreaterThan(tickAtPress + 30);
    const after = await readScene(page);
    expect.soft(boardOf(after), 'nothing was placed: one Source on (23,20), no Factory').toEqual(ONLY_THE_SOURCE);
    expect
      .soft(after.nodes.filter((n) => n.kind === KIND_FACTORY).length, 'no Factory came back')
      .toBe(0);
    await expect
      .configure({ soft: true })
      .poll(async () => {
        const d = await drawnNodesOf(page);
        return { machines: d.machines, strays: d.strays };
      }, { message: 'the machine layer still draws only the Source' })
      .toEqual({ machines: [source.id], strays: 0 });
    expect.soft(await glyphSubjectOn(page, source.id), 'the Source still draws the Source art').toBe('source');
    await expect.soft(undoButton(page), 'Undo is still offered: the step stays on top').toBeEnabled();
    await expectRenderLoopAlive(page, 'after the refused Ctrl+Z');

    // (3) SAVE AS, then OPEN: the board opens again with no refusal card.
    const saved = join(tmpdir(), `fabrico-e2e-86-undo-space-taken-saved-${stamp}.fab`);
    page.once('dialog', (d) => void d.accept(saved));
    await page.getByTitle('Save (Ctrl+S) - Shift for Save As').click({ modifiers: ['Shift'] });
    await expect
      .poll(() => existsSync(saved), {
        timeout: 45_000,
        intervals: [200, 500, 1000],
        message: 'the host wrote the .fab at quiescence (a real save artifact on disk)',
      })
      .toBe(true);
    const savedBoard = boardOf(await readScene(page));
    // New first, so the reopen is a change the poll below can see land.
    await newBoard(page);
    await pollScene(page, (s) => s.nodes.length, { message: 'New cleared the board' }).toBe(0);
    await openThroughToolbar(page, saved);
    await expect
      .configure({ soft: true })
      .poll(async () => boardOf(await readScene(page)), {
        message: 'the saved board opened again with the board it was saved with',
      })
      .toEqual(savedBoard);
    expect.soft(await page.getByRole('alert').count(), 'no refusal card: the saved board opens').toBe(0);
    await waitForCameraSettle(page);
    await expectRenderLoopAlive(page, 'on the reopened board');
    errs.assertNone('across open, Ctrl+Z, save and open');
  });
});
